  // 🚀 الحصول على رد مناسب
  static String getResponse(String message) {
    final lowerMsg = message.toLowerCase();

    // 🔍 البحث عن الكلمات المفتاحية
    String? matchedCategory;
    int maxMatches = 0;

    _keywords.forEach((category, keywords) {
      int matches = 0;
      for (var keyword in keywords) {
        if (lowerMsg.contains(keyword)) {
          matches++;
        }
      }
      if (matches > maxMatches) {
        maxMatches = matches;
        matchedCategory = category;
      }
    });

    // ✅ لو لقى تطابق، يرد بالردود المناسبة
    if (matchedCategory != null && _responses.containsKey(matchedCategory)) {
      final responses = _responses[matchedCategory]!;
      return responses[DateTime.now().millisecondsSinceEpoch %
          responses.length];
    }

    // 🔄 لو ملقتش تطابق، رد عام
    return _getGeneralResponse(message);
  }

